CREATE TABLE users(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone_number VARCHAR(20) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    first_name VARCHAR(255) NOT NULL,
    last_name VARCHAR(255) NOT NULL,
    patronymic VARCHAR(255),
    created_at TIMESTAMP NOT NULL DEFAULT now()
);

CREATE TABLE accounts_types (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_type_id BIGINT NOT NULL REFERENCES accounts_types (id),
    balance BIGINT NOT NULL DEFAULT 0,
    is_system BOOLEAN NOT NULL DEFAULT false,
    created_at TIMESTAMP NOT NULL DEFAULT now(),
    CONSTRAINT accounts_balance_non_negative CHECK (is_system OR balance >= 0)
);

COMMENT ON COLUMN accounts.balance is 'в копейках';
COMMENT ON COLUMN accounts.is_system is 'системный счет банка, баланс может быть отрицательным';

CREATE TABLE users_accounts (
    user_id BIGINT NOT NULL REFERENCES users (id),
    account_id BIGINT NOT NULL REFERENCES accounts (id),
    PRIMARY KEY (user_id, account_id)
);

CREATE INDEX idx_users_accounts_id ON users_accounts (account_id);

CREATE TABLE transfers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    amount BIGINT NOT NULL,
    account_from_id BIGINT NOT NULL REFERENCES accounts (id),
    account_to_id BIGINT NOT NULL REFERENCES accounts (id),
    created_at TIMESTAMP NOT NULL DEFAULT now(),
    CONSTRAINT transfers_amount_positive CHECK (amount > 0),
    CONSTRAINT transfers_different_account CHECK (account_from_id <> account_to_id)
);

COMMENT ON COLUMN transfers.amount IS 'в копейках';

CREATE INDEX idx_transfers_account_from ON transfers (account_from_id);
CREATE INDEX idx_transfers_account_to ON transfers (account_to_id);
CREATE INDEX idx_transfers_created_at ON transfers (created_at);

CREATE TABLE entries(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transfer_id BIGINT NOT NULL REFERENCES transfers (id),
    account_id BIGINT NOT NULL REFERENCES accounts (id),
    amount BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT now(),
    CONSTRAINT entries_amount_not_zero CHECK (amount <> 0)
);

CREATE INDEX idx_entries_tranfer ON entries (transfer_id);
CREATE INDEX idx_entries_account ON entries (account_id);

